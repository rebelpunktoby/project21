function showProject(p) {
  active = p;
  fillDialog(p);
  dBody.classList.toggle("wipe-x", PROJECTS.indexOf(p) % 2 === 1);
  document.body.classList.add("dialog-open");
  if (!dialog.open) dialog.showModal();
  dialog.scrollTop = 0;
}

/* The clicked frame (index plate, or the hero) expands into the case
   study's opening image. Feature-detected; plain open elsewhere. */
function openProject(slug, trigger) {
  const p = PROJECTS.find(x => x.slug === slug);
  if (!p) return;
  if (trigger) lastTrigger = trigger;

  const source = trigger && (trigger.closest(".plate")?.querySelector(".plate-frame")
                          || (trigger.id === "hero-open" ? $("#hero-frame") : null));
  if (!document.startViewTransition || prefersReduced() || !source || dialog.open) {
    showProject(p); return;
  }
  source.style.viewTransitionName = "plate";
  const vt = document.startViewTransition(() => {
    source.style.viewTransitionName = "";
    showProject(p);
    $(".seq--opening", dBody).style.viewTransitionName = "plate";
  });
  vt.finished.finally(() => {
    const o = $(".seq--opening", dBody); if (o) o.style.viewTransitionName = "";
    source.style.viewTransitionName = "";
  });
}

const closeProject = () => { if (dialog.open) dialog.close(); };

/* single cleanup path — also catches Escape */
dialog.addEventListener("close", () => {
  document.body.classList.remove("dialog-open");
  dBody.innerHTML = "";
  active = null;
  if (lastTrigger && document.contains(lastTrigger)) lastTrigger.focus();
  lastTrigger = null;
});

$$(".js-close").forEach(b => b.addEventListener("click", closeProject));
dialog.addEventListener("click", e => { if (e.target === dialog) closeProject(); });
dNext.addEventListener("click", () => {
  if (!dNext.dataset.slug) return;
  showProject(PROJECTS.find(x => x.slug === dNext.dataset.slug));
  dialog.scrollTo({ top: 0, behavior: prefersReduced() ? "auto" : "smooth" });
});

