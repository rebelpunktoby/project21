#!/usr/bin/env python3
"""
PROJECT21 — asset build step.

Run this after adding or changing images in ./projects/:

    python3 tools/build-assets.py

It does two things and touches nothing else:

1. Writes an index thumbnail for each project's cover plate into
   ./thumbs/<slug>.webp (900px wide). The homepage index loads these
   instead of the 1600px originals — the originals are never renamed,
   moved, replaced, or deleted, and the case studies still use them.

2. Rewrites the SIZES / SHEETS manifest block in site.js from what is
   actually on disk, so image counts and dimensions can never drift
   out of sync with the files.

Requires Pillow:  pip install pillow
"""

import glob
import os
import re
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow is required:  pip install pillow")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJECTS = os.path.join(ROOT, "projects")
THUMBS = os.path.join(ROOT, "thumbs")
SITE_JS = os.path.join(ROOT, "site.js")

THUMB_WIDTH = 900
THUMB_QUALITY = 74
KEY = "0123456789abcdefghijklmnopqrstuvwxyz"

BEGIN = "/* == MANIFEST:BEGIN — generated by tools/build-assets.py == */"
END = "/* == MANIFEST:END == */"


def project_slugs():
    return sorted(
        d for d in os.listdir(PROJECTS)
        if os.path.isdir(os.path.join(PROJECTS, d)) and not d.startswith((".", "_"))
    )


def images_for(slug):
    files = sorted(glob.glob(os.path.join(PROJECTS, slug, "[0-9][0-9].webp")))
    expected = [f"{i:02d}.webp" for i in range(1, len(files) + 1)]
    actual = [os.path.basename(f) for f in files]
    if actual != expected:
        sys.exit(
            f"'{slug}' is not numbered contiguously from 01.\n"
            f"  found:    {actual}\n  expected: {expected}"
        )
    return files


def covers_from_site_js(text):
    """Read the cover index each project declares, so we thumbnail the right plate."""
    return {
        m.group(1): int(m.group(2))
        for m in re.finditer(r'slug:\s*"([^"]+)".*?cover:\s*(\d+)', text, re.S)
    }


def main():
    if not os.path.isdir(PROJECTS):
        sys.exit(f"No projects directory at {PROJECTS}")

    site = open(SITE_JS, encoding="utf-8").read()
    covers = covers_from_site_js(site)
    os.makedirs(THUMBS, exist_ok=True)

    slugs = project_slugs()
    sizes, index, sheets = [], {}, {}
    total = 0
    saved_before = saved_after = 0

    for slug in slugs:
        files = images_for(slug)
        if not files:
            print(f"  skip {slug} (no images)")
            continue
        total += len(files)

        chars = ""
        for f in files:
            with Image.open(f) as im:
                wh = im.size
            if wh not in index:
                index[wh] = len(sizes)
                sizes.append(wh)
            chars += KEY[index[wh]]
        sheets[slug] = chars

        # cover thumbnail
        n = covers.get(slug)
        if n is None:
            print(f"  ! {slug}: no cover declared in site.js — skipping thumbnail")
            continue
        srcpath = os.path.join(PROJECTS, slug, f"{n:02d}.webp")
        if not os.path.exists(srcpath):
            sys.exit(f"'{slug}' declares cover {n} but {srcpath} does not exist.")

        out = os.path.join(THUMBS, f"{slug}.webp")
        with Image.open(srcpath) as im:
            im = im.convert("RGB")
            if im.width > THUMB_WIDTH:
                im = im.resize(
                    (THUMB_WIDTH, round(im.height * THUMB_WIDTH / im.width)),
                    Image.LANCZOS,
                )
            im.save(out, "WEBP", quality=THUMB_QUALITY, method=6)

        saved_before += os.path.getsize(srcpath)
        saved_after += os.path.getsize(out)
        print(f"  thumb {slug:18} {os.path.getsize(srcpath)/1024:6.0f} KB -> {os.path.getsize(out)/1024:5.0f} KB")

    if len(sizes) > len(KEY):
        sys.exit(f"Too many distinct image sizes ({len(sizes)}) for the compact manifest.")

    block = [
        BEGIN,
        "const SIZES = [" + ",".join(f"[{w},{h}]" for w, h in sizes) + "];",
        f'const KEY = "{KEY}";',
        "const SHEETS = {",
    ]
    width = max(len(s) for s in sheets) + 3
    for slug, chars in sheets.items():
        block.append(f'  {(chr(34)+slug+chr(34)+":"):<{width}} "{chars}",')
    block[-1] = block[-1].rstrip(",")
    block += ["};", END]
    new_block = "\n".join(block)

    if BEGIN not in site or END not in site:
        sys.exit("Manifest markers not found in site.js — cannot update safely.")
    site = re.sub(
        re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: new_block, site, flags=re.S
    )
    open(SITE_JS, "w", encoding="utf-8").write(site)

    print(f"\n  {len(slugs)} projects · {total} images · {len(sizes)} distinct sizes")
    print(f"  index thumbnails: {saved_before/1024:.0f} KB -> {saved_after/1024:.0f} KB "
          f"({100 - saved_after/max(saved_before,1)*100:.0f}% smaller)")
    print("  site.js manifest updated.\n")


if __name__ == "__main__":
    main()
