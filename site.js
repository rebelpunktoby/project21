/* ------------------------------------------------------------------ *
 * 10. ORIENTATION — active nav link, progress rule
 * ------------------------------------------------------------------ */
function initChapters() {
  const sections = $$("main section[id]");
  const links = $$("[data-chapter]");
  let current = "";

  const setActive = id => {
    if (id === current) return;
    current = id;
    if (id !== "work") setThread(null);
    links.forEach(a => {
      const on = a.dataset.chapter === id;
      a.classList.toggle("is-current", on);
      if (on) a.setAttribute("aria-current", "true"); else a.removeAttribute("aria-current");
    });
  };

  if ("IntersectionObserver" in window) {
    const io = new IntersectionObserver(entries => {
      const hit = entries.filter(e => e.isIntersecting)
        .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
      if (hit) setActive(hit.target.id);
    }, { rootMargin: "-45% 0px -45% 0px", threshold: 0 });
    sections.forEach(s => io.observe(s));
  }

  const progress = $("#chapter-progress");
  let ticking = false;
  const update = () => {
    const max = document.documentElement.scrollHeight - innerHeight;
    progress.style.transform = `scaleX(${max > 0 ? Math.min(1, scrollY / max) : 0})`;
    ticking = false;
  };
  addEventListener("scroll", () => {
    if (!ticking) { ticking = true; requestAnimationFrame(update); }
  }, { passive: true });
  update();
}

/* ------------------------------------------------------------------ *
 * 10a. HERO SEQUENCE — six plates, one at a time. Each slowly drifts,
 * then crossfades; the tick under it runs in that project's accent.
 * Next image is loaded before the swap; pauses off-screen and in a
 * background tab; reduced motion keeps the first plate still.
 * ------------------------------------------------------------------ */
const HERO = [
  ["kokoa", 19, "KOKOA chocolate packaging range"],
  ["durreal", 7, "DURREAL gold durian packaging"],
  ["sorelle", 1, "SORELLE haircare bottles"],
  ["ethereal", 8, "ETHEREAL fragrance packaging in gold, blue and flame colourways"],
  ["baoshu-shigaa", 3, "BAOSHU SIHGAA Traditional Craftsmanship poster"],
  ["a8-recording", 5, "A8 RECORDING 2026 Working poster"]
];
const HERO_MS = 5600;

function initHero() {
  const frame = $("#hero-frame"), tick = $("#hero-tick"), open = $("#hero-open");
  if (!frame) return;
  const project = slug => PROJECTS.find(p => p.slug === slug);
  const setCaption = slug => {
    const p = project(slug);
    open.dataset.slug = slug;
    $(".hero-name", open).textContent = p.title;
    $(".hero-scope", open).innerHTML = `${esc(p.scope.en)} <span lang="zh-Hant">${esc(p.scope.zh)}</span>`;
    $("#hero-plate").style.setProperty("--hero-accent", p.accent);
  };
  open.addEventListener("click", () => openProject(open.dataset.slug, open));
  setCaption(HERO[0][0]);
  if (prefersReduced()) return;

  root.style.setProperty("--hero-ms", HERO_MS + "ms");
  let i = 0, timer = null, visible = true, busy = false;
  const layers = [frame.querySelector("img")];
  layers[0].classList.add("is-first");

  const run = () => { tick.classList.remove("is-running"); void tick.offsetWidth; tick.classList.add("is-running"); };
  const advance = () => {
    if (busy) return;
    busy = true;
    const n = (i + 1) % HERO.length;
    const [slug, num, alt] = HERO[n];
    let img = layers[n];
    const show = () => {
      const prev = layers[i];
      prev.classList.remove("is-on", "is-first");
      prev.classList.add("was-on");
      setTimeout(() => prev.classList.remove("was-on"), 1000);   /* after the wipe */
      void img.offsetWidth;                 /* restart the animations */
      img.classList.add("is-on");
      open.classList.add("is-swapping");
      setTimeout(() => { setCaption(slug); open.classList.remove("is-swapping"); }, 350);
      i = n; busy = false; run();
    };
    if (img) { show(); return; }
    img = new Image();
    img.decoding = "async"; img.alt = alt + ", by PROJECT21";
    img.src = src(slug, num);
    layers[n] = img;
    frame.appendChild(img);
    (img.decode ? img.decode() : Promise.resolve()).then(show, () => { layers[n] = null; img.remove(); busy = false; });
  };
  const start = () => { if (!timer && visible && !document.hidden) { run(); timer = setInterval(advance, HERO_MS); } };
  const stop  = () => { clearInterval(timer); timer = null; tick.classList.remove("is-running"); };

  if ("IntersectionObserver" in window) {
    new IntersectionObserver(([e]) => { visible = e.isIntersecting; visible ? start() : stop(); })
      .observe($("#hero-plate"));
  }
  document.addEventListener("visibilitychange", () => document.hidden ? stop() : start());
  start();
}

/* cursor cue: on fine pointers the "Open" label follows the cursor inside
   the frame (CSS positions it from --cx/--cy; this only writes them). */
function initCursorCue(scope) {
  if (!matchMedia("(hover: hover) and (pointer: fine)").matches) return;
  $$(".plate-frame", scope).forEach(frame => {
    frame.addEventListener("pointermove", e => {
      const r = frame.getBoundingClientRect();
      frame.style.setProperty("--cx", (e.clientX - r.left) + "px");
      frame.style.setProperty("--cy", (e.clientY - r.top) + "px");
    }, { passive: true });
  });
}

/* plate peek: on hover, an image from inside the project fades over the
   title plate. Loaded on first hover only; fine pointers only. */
function initPeek(scope) {
  if (prefersReduced() || !matchMedia("(hover: hover) and (pointer: fine)").matches) return;
  $$(".plate", scope).forEach(el => {
    el.addEventListener("pointerenter", () => {
      if (el.dataset.peeked) return;
      el.dataset.peeked = "1";
      const p = PROJECTS.find(x => x.slug === el.dataset.slug);
      const n = p.cover === 1 ? 2 : 1;
      const img = new Image();
      img.className = "plate-peek"; img.alt = ""; img.decoding = "async";
      img.src = src(p.slug, n);
      $(".plate-frame", el).insertBefore(img, $(".plate-cue", el));
      img.decode().then(() => img.classList.add("is-ready"), () => img.remove());
    });
  });
}

/* ------------------------------------------------------------------ *
 * 10b. ACCENT THREAD — the header rule borrows the accent of the
 * project nearest the middle of the viewport; nothing else does.
 * ------------------------------------------------------------------ */
const root = document.documentElement;
let threadIO = null;
function setThread(colour) {
  if (colour) root.style.setProperty("--thread", colour);
  else root.style.removeProperty("--thread");
}
function observeThread(scope) {
  if (!("IntersectionObserver" in window) || prefersReduced()) return;
  if (!threadIO) {
    threadIO = new IntersectionObserver(entries => {
      const hit = entries.filter(e => e.isIntersecting)
        .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
      if (hit) setThread(hit.target.style.getPropertyValue("--accent"));
    }, { rootMargin: "-40% 0px -40% 0px", threshold: 0 });
  } else {
    threadIO.disconnect();
  }
  $$(".plate", scope).forEach(el => threadIO.observe(el));
}

/* ------------------------------------------------------------------ *
 * 11. MOTION — reveals and image error fallback
 * Images are never hidden while loading, and every reveal has a
 * time fallback, so a full-page capture or a tall viewport always
 * shows the whole page.
 * ------------------------------------------------------------------ */
const prefersReduced = () =>
  "matchMedia" in window && matchMedia("(prefers-reduced-motion: reduce)").matches;

function watchImages(scope) {
  $$("img", scope).forEach(img => {
    img.addEventListener("error", () => {
      const holder = img.closest(".plate-frame, .seq, .pair-cell, .hero-plate");
      if (holder) holder.classList.add("image-error");
    }, { once: true });
  });
}

/* .reveal (section heads) and .rise (plates, when the browser has no
   scroll-driven animations) share one observer. */
let revealIO = null;
const showAll = scope => $$(".reveal, .rise", scope).forEach(n => n.classList.add("is-visible"));

function observeRises(scope) {
  if (!revealIO) { showAll(scope); return; }
  $$(".rise", scope).forEach(n => revealIO.observe(n));
  setTimeout(() => showAll(scope), 1400);
}

function initReveals() {
  if (prefersReduced() || !("IntersectionObserver" in window)) { showAll(document); return; }
  revealIO = new IntersectionObserver(entries => {
    entries.forEach(e => {
      if (e.isIntersecting) { e.target.classList.add("is-visible"); revealIO.unobserve(e.target); }
    });
  }, { rootMargin: "0px 0px -6%", threshold: 0.01 });
  $$(".reveal, .rise").forEach(n => revealIO.observe(n));
  /* fallback: nothing stays hidden for long, whatever the viewport does */
  setTimeout(() => showAll(document), 1400);
}

