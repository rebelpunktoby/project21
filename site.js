/* ------------------------------------------------------------------ *
 * 7. CASE STUDY SEQUENCING
 * Built from real orientations: wide images take the full measure,
 * uprights of similar shape pair up, and one pause sits near the
 * middle. Nothing runs until a project is opened.
 * ------------------------------------------------------------------ */
const classify = r => (r >= 1.7 ? "full" : r >= 1.2 ? "wide" : r >= 0.95 ? "square" : "tall");

function buildSequence(p) {
  const all = sheet(p.slug);
  const opening = all.find(x => x.n === p.cover);
  const rest = all.filter(x => x.n !== p.cover);
  const blocks = [];

  for (let i = 0; i < rest.length; i++) {
    const a = rest[i], ka = classify(a.r);
    const b = rest[i + 1], kb = b && classify(b.r);
    const pairable = k => k === "tall" || k === "square";
    if (pairable(ka) && pairable(kb) && Math.abs(a.r - b.r) < 0.28) {
      blocks.push({ kind: "pair", items: [a, b] });
      i++;
    } else {
      blocks.push({ kind: ka, items: [a] });
    }
  }

  if (blocks.length > 5) blocks.splice(Math.round(blocks.length / 2), 0, { kind: "pause", items: [] });
  return { opening, blocks };
}

function sequenceHTML(p) {
  const { opening, blocks } = buildSequence(p);
  let n = 0;
  const alt = i => `${p.title} — case study image ${i}`;

  const head = `<figure class="seq seq--opening">${imgTag(p.slug, opening, `${p.title} — title plate`, true)}</figure>`;

  const body = blocks.map(b => {
    if (b.kind === "pause") return `<div class="seq seq--pause" aria-hidden="true"><span class="pause-rule"></span></div>`;
    if (b.kind === "pair") {
      return `<div class="seq seq--pair">${b.items.map(it =>
        `<figure class="pair-cell">${imgTag(p.slug, it, alt(++n), n === 1)}</figure>`).join("")}</div>`;
    }
    return `<figure class="seq seq--${b.kind}">${imgTag(p.slug, b.items[0], alt(++n), n === 1)}</figure>`;
  }).join("");

  return head + body;
}

