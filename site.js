function sheet(slug) {
  return SHEETS[slug].split("").map((ch, i) => {
    const [w, h] = SIZES[KEY.indexOf(ch)];
    return { n: i + 1, w, h, r: w / h };
  });
}
const src = (slug, n) => `./projects/${slug}/${String(n).padStart(2, "0")}.webp`;

/* Index thumbnails written by tools/build-assets.py. The 1600px original
   stays the src, so a missing thumbnail degrades instead of breaking; the
   browser picks the 900px file for the small slots the index actually uses. */
const thumb = slug => `./thumbs/${slug}.webp`;
const COVER_SIZES = "(max-width: 620px) calc(100vw - 2.2rem), (max-width: 1180px) 46vw, 30vw";
function coverAttrs(p, cov) {
  return `src="${src(p.slug, p.cover)}" srcset="${thumb(p.slug)} 900w, ${src(p.slug, p.cover)} ${cov.w}w" ` +
         `sizes="${COVER_SIZES}" width="${cov.w}" height="${cov.h}"`;
}
const esc = s => String(s).replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

function imgTag(slug, item, alt, eager) {
  return `<img src="${src(slug, item.n)}" width="${item.w}" height="${item.h}" alt="${esc(alt)}" ` +
         `loading="${eager ? "eager" : "lazy"}" decoding="async"${eager ? ' fetchpriority="high"' : ""}>`;
}

