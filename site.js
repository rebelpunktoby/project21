function observeThread(scope) {
  /* also runs under reduced motion: the thread and tint then change without transition */
  if (!("IntersectionObserver" in window)) return;
  if (!threadIO) {
    threadIO = new IntersectionObserver(entries => {
      const hit = entries.filter(e => e.isIntersecting)
        .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
      if (hit) { setThread(hit.target.style.getPropertyValue("--accent")); setKaleidoSource(hit.target.dataset.slug); weather.set(hit.target.dataset.slug); }
    }, { rootMargin: "-40% 0px -40% 0px", threshold: 0 });
  } else {
    threadIO.disconnect();
  }
  $$(".plate", scope).forEach(el => threadIO.observe(el));
}

/* ------------------------------------------------------------------ *
 * 11. MOTION — reveals and image error fallback
 * Images are never hidden while loading, and every reveal has a
 * time fallback, so a full-page capture or a tall viewport always
 * shows the whole page.
 * ------------------------------------------------------------------ */
const prefersReduced = () =>
  "matchMedia" in window && matchMedia("(prefers-reduced-motion: reduce)").matches;

function watchImages(scope) {
  $$("img", scope).forEach(img => {
    img.addEventListener("error", () => {
      const holder = img.closest(".plate-frame, .seq, .pair-cell, .hero-plate");
      if (holder) holder.classList.add("image-error");
    }, { once: true });
  });
}

/* .reveal (section heads) and .rise (plates, when the browser has no
   scroll-driven animations) share one observer. */
let revealIO = null;
const showAll = scope => $$(".reveal, .rise", scope).forEach(n => n.classList.add("is-visible"));

function observeRises(scope) {
  if (!revealIO) { showAll(scope); return; }
  $$(".rise", scope).forEach(n => revealIO.observe(n));
  setTimeout(() => showAll(scope), 1400);
}

function initReveals() {
  if (prefersReduced() || !("IntersectionObserver" in window)) { showAll(document); return; }
  revealIO = new IntersectionObserver(entries => {
    entries.forEach(e => {
      if (e.isIntersecting) { e.target.classList.add("is-visible"); revealIO.unobserve(e.target); }
    });
  }, { rootMargin: "0px 0px -6%", threshold: 0.01 });
  $$(".reveal, .rise").forEach(n => revealIO.observe(n));
  /* fallback: nothing stays hidden for long, whatever the viewport does */
  setTimeout(() => showAll(document), 1400);
}

